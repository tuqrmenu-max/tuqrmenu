export const useI18n = create((set, get) => ({
  lang: 'es',
  
  setLang: (lang) => set({ lang }),
  
  t: (key) => {
    const { lang } = get()
    return translations[lang]?.[key] || translations.es[key] || key
  },
  
  toggleLang: () => {
    const { lang } = get()
    set({ lang: lang === 'es' ? 'en' : 'es' })
  }
}))
